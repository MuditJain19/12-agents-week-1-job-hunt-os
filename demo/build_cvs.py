"""Assemble the checked CVs (PDF), check reports and updated tracker for the demo."""
import csv, json, html, pathlib
from playwright.sync_api import sync_playwright

root = pathlib.Path(__file__).resolve().parent.parent
drafts = json.loads((root / "demo/drafts.json").read_text())
verdicts = json.loads((root / "demo/verdicts.json").read_text())
numbers = json.loads((root / "demo/number_check.json").read_text())
profile = json.loads((root / "templates/profile.example.json").read_text())

ROLE_OF = {"F05": "mgr", "F06": "mgr", "F07": "mgr", "F08": "mgr", "F09": "sr", "F10": "sr", "F11": "an"}
ROLES = [("mgr", "Growth Analytics Manager", "Jan 2025 to Aug 2026"),
         ("sr", "Senior Analyst", "Jul 2022 to Dec 2024"),
         ("an", "Analyst", "Jul 2020 to Jun 2022")]
KEY = {"tiffinly": ("tiffinly", "Tiffinly", "Growth Analytics Manager"),
       "kirana": ("kirana", "Kirana Cloud", "Analytics Manager"),
       "souk": ("souk", "Souk Express", "Manager, Growth & Retention")}
CSS = """body{font-family:Georgia,serif;color:#1d1d1f;margin:42px 54px;font-size:11pt;line-height:1.4}
h1{font-size:20pt;margin:0}.contact{color:#555;font-size:9.5pt;margin:4px 0 14px}
h2{font-size:10.5pt;letter-spacing:.08em;text-transform:uppercase;border-bottom:1px solid #ccc;padding-bottom:3px;margin:16px 0 6px}
.role{display:flex;justify-content:space-between;font-weight:bold;margin-top:8px}.dates{font-weight:normal;color:#555}
ul{margin:4px 0 0 18px;padding:0}li{margin:2px 0}.tag{color:#888;font-size:8.5pt}
.banner{background:#fff4d6;border:1px solid #e0c36a;padding:6px 10px;font-size:9pt;margin-bottom:14px}"""

results = {}
with sync_playwright() as p:
    browser = p.chromium.launch()
    for k, d in drafts.items():
        v = {r["i"]: r for r in verdicts[k]}
        kept, removed = [], []
        for i, line in enumerate(d["lines"]):
            num = numbers[k][i]
            ok = v[i]["verdict"] == "supported" and num["ok"]
            reason = v[i].get("problem", "")
            if not num["ok"] and num["numbers_not_in_cited_facts"]:
                reason = (reason + " " if reason else "") + "Number check: " + ", ".join(num["numbers_not_in_cited_facts"]) + " not in cited facts."
            (kept if ok else removed).append((line, reason))
        refills = verdicts.get("replacements", {}).get(k, [])
        for rep in refills:
            if rep["part"] == "summary":
                kept.insert(0, (rep, ""))
            else:
                kept.append((rep, ""))
        summary = " ".join(l["text"] for l, _ in kept if l["part"] == "summary")
        skills = " ".join(l["text"] for l, _ in kept if l["part"] == "skills")
        by_role = {r[0]: [] for r in ROLES}
        for l, _ in kept:
            if l["part"] == "bullet":
                by_role[ROLE_OF.get(l["ids"][0], "mgr")].append(l["text"])
        roles_html = "".join(
            f'<div class="role"><span>{t}, Dicebox Games, Bengaluru</span><span class="dates">{dt}</span></div>'
            + ("<ul>" + "".join(f"<li>{html.escape(b)}</li>" for b in by_role[rk]) + "</ul>" if by_role[rk] else "")
            for rk, t, dt in ROLES)
        doc = f"""<html><head><meta charset="utf-8"><style>{CSS}</style></head><body>
<div class="banner">SAMPLE CV for a fictional person (Asha Rao), generated by Job Hunt OS for {html.escape(d['company'])} (fictional company).</div>
<h1>{profile['name']}</h1><div class="contact">{profile['headline']} | {profile['location']} | {profile['email']} | {profile['linkedin']}</div>
<h2>Summary</h2><p>{html.escape(summary)}</p>
<h2>Experience</h2>{roles_html}
<h2>Skills</h2><p>{html.escape(skills)}</p>
<h2>Education</h2><p>B.Tech Computer Science, Northfield Institute of Technology (fictional), 2020</p></body></html>"""
        stem = f"{d['company'].replace(' ', '')}_{d['role'].replace(',', '').replace(' & ', '_').replace(' ', '')}"
        page = browser.new_page()
        page.set_content(doc)
        page.pdf(path=str(root / f"demo/cvs/{stem}_CV.pdf"), format="A4", margin={"top": "0", "bottom": "0", "left": "0", "right": "0"})
        page.close()
        rep = [f"# Check report: {d['company']}, {d['role']} (sample)", "",
               f"**Fit score:** {d['fit_score']}/100", "", "**Why it fits**"] + [f"- {r}" for r in d["reasons"]] + \
              ["", "**Gaps**"] + [f"- {g}" for g in d["gaps"]] + \
              ["", f"**Lines checked:** {len(d['lines'])}  |  **Removed:** {len(removed)}  |  **Refilled from other facts and re-checked:** {len(refills)}", ""]
        if removed:
            rep += ["| Removed line | Cited | Why |", "|---|---|---|"] + \
                   [f"| {l['text']} | {', '.join(l['ids'])} | {r} |" for l, r in removed]
        else:
            rep += ["No lines removed."]
        (root / f"demo/cvs/{stem}_check.md").write_text("\n".join(rep) + "\n")
        results[d["company"]] = {"fit": d["fit_score"], "pdf": f"demo/cvs/{stem}_CV.pdf", "removed": len(removed), "checked": len(d["lines"])}
    browser.close()

rows = list(csv.DictReader(open(root / "demo/tracker.csv")))
for r in rows:
    if r["filter_result"] == "shortlist":
        if r["company"] in results:
            res = results[r["company"]]
            r.update(decision="Interested", fit_score=str(res["fit"]), cv_link=res["pdf"], status="cv_ready",
                     notes=f"check removed {res['removed']} of {res['checked']} lines")
        elif r["company"] == "Streamly":
            r.update(decision="Skip", status="skipped", notes="not interested in streaming")
with open(root / "demo/tracker.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)
print(json.dumps(results, indent=1))
